function formatTanggal(iso, long = false) {
  if (!iso) return "-";
  const [y, m, d] = String(iso).split("-").map(Number);
  return new Intl.DateTimeFormat("id-ID", {
    day: long ? "numeric" : "2-digit",
    month: long ? "long" : "short",
    year: "numeric",
  }).format(new Date(y, m - 1, d));
}

